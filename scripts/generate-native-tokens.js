#!/usr/bin/env node
/**
 * Writes theme/tokens.js colours as an Android resource file for the widgets and
 * the live-budget notification, so native colours are the same values as the
 * app's. Run after changing the token module:
 *
 *   node scripts/generate-native-tokens.js
 *
 * tests/nativeTokens.test.ts fails if the checked-in XML is out of date.
 */
const fs = require('fs');
const path = require('path');
const { colors } = require('../theme/tokens');

const OUT = path.join(__dirname, '..', 'modules', 'flowe-notifications', 'android', 'src', 'main', 'res', 'values', 'flowe_tokens.xml');

/** '#rrggbb' | '#rrggbbaa' | 'rgba(r,g,b,a)' → Android '#AARRGGBB'. */
function toAndroid(value) {
  const hex = (n) => n.toString(16).padStart(2, '0').toUpperCase();
  const rgba = /^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)$/.exec(value);
  if (rgba) {
    const [, r, g, b, a] = rgba;
    return '#' + hex(Math.round(Number(a) * 255)) + hex(Number(r)) + hex(Number(g)) + hex(Number(b));
  }
  const h = value.replace('#', '').toUpperCase();
  if (h.length === 6) return '#FF' + h;
  if (h.length === 8) return '#' + h.slice(6) + h.slice(0, 6);
  throw new Error('Unsupported colour ' + value);
}

function render() {
  const lines = Object.entries(colors).map(
    ([name, value]) => `  <color name="flowe_${name.replace(/-/g, '_')}">${toAndroid(value)}</color>`,
  );
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- GENERATED by scripts/generate-native-tokens.js from theme/tokens.js. Do not edit. -->',
    '<resources>',
    ...lines,
    '</resources>',
    '',
  ].join('\n');
}

module.exports = { render, toAndroid, OUT };

if (require.main === module) {
  fs.writeFileSync(OUT, render());
  console.log('wrote', path.relative(process.cwd(), OUT));
}
